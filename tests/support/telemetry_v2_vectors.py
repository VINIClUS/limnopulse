"""Loader for the P2 cross-language telemetry vectors.

`testdata/telemetry_v2/contract_vectors.json` is generated by
`scripts/dev/export_telemetry_v2_vectors.py`; never edit it by hand.
"""

import json
from collections.abc import Mapping
from dataclasses import dataclass
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any

from limnopulse_api.domain.telemetry_v2 import (
    CanonicalObservation,
    SourceType,
    observation_event_id,
)
from limnopulse_api.domain.telemetry_v2_schema import (
    build_legacy_points,
    encode_legacy_line,
    encode_observation_line,
)

VECTORS_PATH = Path(__file__).resolve().parents[2] / "testdata/telemetry_v2/contract_vectors.json"
REBASE_LEAD = timedelta(seconds=1)


@dataclass(frozen=True)
class TelemetryScenario:
    name: str
    description: str
    tenant_id: str
    source_type: SourceType
    devices: tuple[str, ...]
    components: tuple[str, ...]
    legacy_pond_by_asset: Mapping[str, str]
    observations: tuple[CanonicalObservation, ...]
    v2_lines: tuple[str, ...]
    legacy_lines: tuple[str, ...]

    @property
    def legacy_count(self) -> int:
        return len(self.legacy_lines)

    def rebased(self, now: datetime) -> "TelemetryScenario":
        """Shift every timestamp uniformly so the latest `observed_at` is `now - 1 s`.

        Spacing and delays are preserved; event IDs and lines are recomputed through the
        production encoders, so a relative-window test can seed them against a captured `now`.
        """
        if now.tzinfo is None or now.utcoffset() is None:
            raise ValueError("now must be timezone-aware")
        latest = max(item.observation.observed_at for item in self.observations)
        delta = (now - REBASE_LEAD) - latest
        observations = tuple(_shift(item, delta) for item in self.observations)
        return TelemetryScenario(
            name=self.name,
            description=self.description,
            tenant_id=self.tenant_id,
            source_type=self.source_type,
            devices=self.devices,
            components=self.components,
            legacy_pond_by_asset=self.legacy_pond_by_asset,
            observations=observations,
            v2_lines=encode_v2_lines(observations),
            legacy_lines=encode_legacy_lines(observations, self.legacy_pond_by_asset),
        )


def encode_v2_lines(observations: tuple[CanonicalObservation, ...]) -> tuple[str, ...]:
    return tuple(encode_observation_line(item) for item in observations)


def encode_legacy_lines(
    observations: tuple[CanonicalObservation, ...], legacy_pond_by_asset: Mapping[str, str]
) -> tuple[str, ...]:
    return tuple(
        encode_legacy_line(point)
        for point in build_legacy_points(observations, legacy_pond_by_asset)
    )


def _shift(item: CanonicalObservation, delta: timedelta) -> CanonicalObservation:
    data = item.model_dump()
    observed_at = data["observation"]["observed_at"] + delta
    data["observation"]["observed_at"] = observed_at
    data["source"]["received_at"] += delta
    data["delivery"]["ingested_at"] += delta
    data["event_id"] = observation_event_id(
        data["resolved"]["tenant_id"],
        data["resolved"]["component_id"],
        data["observation"]["metric_key"],
        observed_at,
    )
    return CanonicalObservation.model_validate(data)


def load_vectors() -> dict[str, Any]:
    """Return a fresh copy of the whole vector document."""
    return json.loads(VECTORS_PATH.read_text(encoding="utf-8"))


def scenario(name: str) -> TelemetryScenario:
    raw = load_vectors()["scenarios"][name]
    return TelemetryScenario(
        name=name,
        description=raw["description"],
        tenant_id=raw["tenant_id"],
        source_type=SourceType(raw["source_type"]),
        devices=tuple(raw["devices"]),
        components=tuple(raw["components"]),
        legacy_pond_by_asset=dict(raw["legacy_pond_by_asset"]),
        observations=tuple(
            CanonicalObservation.model_validate(item) for item in raw["observations"]
        ),
        v2_lines=tuple(raw["v2_lines"]),
        legacy_lines=tuple(raw["legacy_lines"]),
    )
