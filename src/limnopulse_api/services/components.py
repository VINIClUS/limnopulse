from collections.abc import Callable
from datetime import datetime

from pydantic import BaseModel, ConfigDict, Field, model_validator

from limnopulse_api.adapters.dynamodb_v2 import utc_now
from limnopulse_api.core.errors import ConflictError, NotFoundError
from limnopulse_api.domain.devices_v2 import (
    ActuatorProfile,
    ComponentKind,
    ComponentStatus,
    DeviceComponent,
    DeviceStatus,
    DeviceV2,
    ProbeProfile,
    ensure_component_transition,
)
from limnopulse_api.domain.ids import (
    new_actuator_profile_id,
    new_component_id,
    new_probe_profile_id,
    require_safe_id,
)
from limnopulse_api.repositories.v2_contracts import DeviceComponentRepository
from limnopulse_api.services.devices_v2 import (
    NAME_MAX_LENGTH,
    TEXT_MAX_LENGTH,
    CreateOutcome,
    create_idempotently,
    is_valid_device_id,
)

COMPONENT_CREATE_SCOPE = "component-create"


def is_valid_component_id(component_id: str) -> bool:
    try:
        require_safe_id(component_id)
    except ValueError:
        return False
    return True


class ProbeProfileCommand(BaseModel):
    """Probe profile fields; the profile ID is generated by the server."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    serial_number: str | None = Field(default=None, min_length=1, max_length=TEXT_MAX_LENGTH)
    measurement_metric_keys: tuple[str, ...] = ()


class ActuatorProfileCommand(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    actuator_type: str = Field(min_length=1, max_length=TEXT_MAX_LENGTH)


class ComponentCreateCommand(BaseModel):
    """`kind`, profiles and model profile are immutable after creation."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    kind: ComponentKind
    name: str = Field(min_length=1, max_length=NAME_MAX_LENGTH)
    model_profile_key: str | None = Field(default=None, min_length=1, max_length=TEXT_MAX_LENGTH)
    probe_profile: ProbeProfileCommand | None = None
    actuator_profile: ActuatorProfileCommand | None = None

    @model_validator(mode="after")
    def validate_kind_profiles(self) -> "ComponentCreateCommand":
        needs_probe = self.kind in {ComponentKind.PROBE, ComponentKind.HYBRID}
        needs_actuator = self.kind in {ComponentKind.ACTUATOR, ComponentKind.HYBRID}
        if needs_probe != (self.probe_profile is not None):
            raise ValueError(f"{self.kind} component probe_profile mismatch")
        if needs_actuator != (self.actuator_profile is not None):
            raise ValueError(f"{self.kind} component actuator_profile mismatch")
        return self


class ComponentUpdateCommand(BaseModel):
    """Only `name` and `status` are mutable; `None` leaves a field unchanged."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    expected_version: int = Field(ge=1)
    name: str | None = Field(default=None, min_length=1, max_length=NAME_MAX_LENGTH)
    status: ComponentStatus | None = None


class ComponentService:
    def __init__(
        self,
        repository: DeviceComponentRepository,
        *,
        clock: Callable[[], datetime] = utc_now,
        id_factory: Callable[[], str] = new_component_id,
        probe_profile_id_factory: Callable[[], str] = new_probe_profile_id,
        actuator_profile_id_factory: Callable[[], str] = new_actuator_profile_id,
    ) -> None:
        self.repository = repository
        self.clock = clock
        self.id_factory = id_factory
        self.probe_profile_id_factory = probe_profile_id_factory
        self.actuator_profile_id_factory = actuator_profile_id_factory

    async def list(self, tenant_id: str, device_id: str) -> list[DeviceComponent]:
        await self._require_device(tenant_id, device_id)
        return await self.repository.list_components(tenant_id, device_id)

    async def get(self, tenant_id: str, component_id: str) -> DeviceComponent | None:
        if not is_valid_component_id(component_id):
            return None
        return await self.repository.get_component(tenant_id, component_id)

    async def create(
        self,
        tenant_id: str,
        device_id: str,
        command: ComponentCreateCommand,
        idempotency_key: str,
    ) -> CreateOutcome[DeviceComponent]:
        async def build() -> DeviceComponent:
            device = await self._require_device(tenant_id, device_id)
            if device.status is DeviceStatus.DECOMMISSIONED:
                raise ConflictError("device is decommissioned")
            now = self.clock()
            return DeviceComponent(
                tenant_id=tenant_id,
                component_id=self.id_factory(),
                device_id=device_id,
                kind=command.kind,
                name=command.name,
                model_profile_key=command.model_profile_key,
                probe_profile=(
                    None
                    if command.probe_profile is None
                    else ProbeProfile(
                        probe_profile_id=self.probe_profile_id_factory(),
                        serial_number=command.probe_profile.serial_number,
                        measurement_metric_keys=command.probe_profile.measurement_metric_keys,
                    )
                ),
                actuator_profile=(
                    None
                    if command.actuator_profile is None
                    else ActuatorProfile(
                        actuator_profile_id=self.actuator_profile_id_factory(),
                        actuator_type=command.actuator_profile.actuator_type,
                    )
                ),
                status=ComponentStatus.ACTIVE,
                created_at=now,
                updated_at=now,
                version=1,
            )

        return await create_idempotently(
            self.repository,
            tenant_id=tenant_id,
            scope=COMPONENT_CREATE_SCOPE,
            idempotency_key=idempotency_key,
            request_payload={
                "tenant_id": tenant_id,
                "device_id": device_id,
                "body": command.model_dump(mode="json"),
            },
            entity_type=DeviceComponent,
            build=build,
            persist=self.repository.create_component,
            clock=self.clock,
        )

    async def update(
        self, tenant_id: str, component_id: str, command: ComponentUpdateCommand
    ) -> DeviceComponent:
        current = await self.get(tenant_id, component_id)
        if current is None:
            raise NotFoundError("component not found")
        if command.status is not None:
            ensure_component_transition(current.status, command.status)
        return await self.repository.update_component(
            tenant_id,
            component_id,
            command.expected_version,
            name=command.name,
            status=command.status,
        )

    async def _require_device(self, tenant_id: str, device_id: str) -> DeviceV2:
        device = None
        if is_valid_device_id(device_id):
            device = await self.repository.get_device(tenant_id, device_id)
        if device is None:
            raise NotFoundError("device not found")
        return device
